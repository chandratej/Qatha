import 'package:cloud_firestore/cloud_firestore.dart';
import '../../../domain/entities/story.dart';

class StoryModel extends Story {
  const StoryModel({
    required super.id,
    required super.title,
    required super.description,
    required super.authorId,
    required super.authorName,
    required super.coverUrl,
    required super.genres,
    required super.tags,
    required super.leagueId,
    required super.status,
    required super.isCompleted,
    required super.language,
    required super.wordCount,
    required super.chapterCount,
    required super.readerCount,
    required super.completionRate,
    required super.averageRating,
    required super.ratingCount,
    required super.reviewCount,
    required super.favoriteCount,
    required super.commentCount,
    required super.createdAt,
    required super.updatedAt,
    required super.publishedAt,
    required super.lastReadAt,
    required super.isPremium,
    required super.unlockPrice,
    required super.audioAvailable,
    required super.qualityScore,
    required super.promotionHistory,
    required super.metrics,
  });

  factory StoryModel.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return StoryModel(
      id: doc.id,
      title: data['title'] ?? 'Untitled',
      description: data['description'] ?? '',
      authorId: data['authorId'] ?? '',
      authorName: data['authorName'] ?? 'Unknown Author',
      coverUrl: data['coverUrl'] ?? '',
      genres: List<String>.from(data['genres'] ?? []),
      tags: List<String>.from(data['tags'] ?? []),
      leagueId: data['leagueId'] ?? 'manuscript',
      status: StoryStatus.values.firstWhere(
        (e) => e.name == data['status'],
        orElse: () => StoryStatus.ongoing,
      ),
      isCompleted: data['isCompleted'] ?? false,
      language: data['language'] ?? 'en',
      wordCount: data['wordCount'] ?? 0,
      chapterCount: data['chapterCount'] ?? 0,
      readerCount: data['readerCount'] ?? 0,
      completionRate: (data['completionRate'] ?? 0.0).toDouble(),
      averageRating: (data['averageRating'] ?? 0.0).toDouble(),
      ratingCount: data['ratingCount'] ?? 0,
      reviewCount: data['reviewCount'] ?? 0,
      favoriteCount: data['favoriteCount'] ?? 0,
      commentCount: data['commentCount'] ?? 0,
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      updatedAt: (data['updatedAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      publishedAt: (data['publishedAt'] as Timestamp?)?.toDate(),
      lastReadAt: (data['lastReadAt'] as Timestamp?)?.toDate(),
      isPremium: data['isPremium'] ?? false,
      unlockPrice: (data['unlockPrice'] ?? 0.0).toDouble(),
      audioAvailable: data['audioAvailable'] ?? false,
      qualityScore: (data['qualityScore'] ?? 0.0).toDouble(),
      promotionHistory: List<String>.from(data['promotionHistory'] ?? []),
      metrics: StoryMetrics.fromMap(data['metrics'] ?? {}),
    );
  }

  static StoryModel fromEntity(Story story) {
    return StoryModel(
      id: story.id,
      title: story.title,
      description: story.description,
      authorId: story.authorId,
      authorName: story.authorName,
      coverUrl: story.coverUrl,
      genres: story.genres,
      tags: story.tags,
      leagueId: story.leagueId,
      status: story.status,
      isCompleted: story.isCompleted,
      language: story.language,
      wordCount: story.wordCount,
      chapterCount: story.chapterCount,
      readerCount: story.readerCount,
      completionRate: story.completionRate,
      averageRating: story.averageRating,
      ratingCount: story.ratingCount,
      reviewCount: story.reviewCount,
      favoriteCount: story.favoriteCount,
      commentCount: story.commentCount,
      createdAt: story.createdAt,
      updatedAt: story.updatedAt,
      publishedAt: story.publishedAt,
      lastReadAt: story.lastReadAt,
      isPremium: story.isPremium,
      unlockPrice: story.unlockPrice,
      audioAvailable: story.audioAvailable,
      qualityScore: story.qualityScore,
      promotionHistory: story.promotionHistory,
      metrics: story.metrics,
    );
  }
}
