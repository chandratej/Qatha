import 'package:cloud_firestore/cloud_firestore.dart';
import '../../../domain/entities/story.dart';
import '../models/author_model.dart';

class StoryModel extends Story {
  const StoryModel({
    required super.id,
    required super.title,
    required super.description,
    required super.authorId,
    required super.authorName,
    required super.coverUrl,
    required super.genres,
    required super.tags,
    required super.league,
    required super.status,
    required super.language,
    required super.wordCount,
    required super.chapterCount,
    required super.readerCount,
    required super.completionRate,
    required super.averageRating,
    required super.ratingCount,
    required super.reviewCount,
    required super.favoriteCount,
    required super.commentCount,
    required super.createdAt,
    required super.updatedAt,
    required super.publishedAt,
    required super.lastReadAt,
    required super.isPremium,
    required super.unlockPrice,
    required super.audioAvailable,
    required super.qualityScore,
    required super.promotionHistory,
    required super.metrics,
  });

  factory StoryModel.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return StoryModel(
      id: doc.id,
      title: data['title'] ?? 'Untitled',
      description: data['description'] ?? '',
      authorId: data['authorId'] ?? '',
      authorName: data['authorName'] ?? 'Unknown Author',
      coverUrl: data['coverUrl'] ?? '',
      genres: List<String>.from(data['genres'] ?? []),
      tags: List<String>.from(data['tags'] ?? []),
      league: data['league'] ?? 'manuscript',
      status: StoryStatus.values.firstWhere(
        (e) => e.name == data['status'],
        orElse: () => StoryStatus.ongoing,
      ),
      language: data['language'] ?? 'en',
      wordCount: data['wordCount'] ?? 0,
      chapterCount: data['chapterCount'] ?? 0,
      readerCount: data['readerCount'] ?? 0,
      completionRate: (data['completionRate'] ?? 0.0).toDouble(),
      averageRating: (data['averageRating'] ?? 0.0).toDouble(),
      ratingCount: data['ratingCount'] ?? 0,
      reviewCount: data['reviewCount'] ?? 0,
      favoriteCount: data['favoriteCount'] ?? 0,
      commentCount: data['commentCount'] ?? 0,
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      updatedAt: (data['updatedAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      publishedAt: (data['publishedAt'] as Timestamp?)?.toDate(),
      lastReadAt: (data['lastReadAt'] as Timestamp?)?.toDate(),
      isPremium: data['isPremium'] ?? false,
      unlockPrice: data['unlockPrice'] ?? 0.0,
      audioAvailable: data['audioAvailable'] ?? false,
      qualityScore: (data['qualityScore'] ?? 0.0).toDouble(),
      promotionHistory: List<String>.from(data['promotionHistory'] ?? []),
      metrics: StoryMetrics.fromMap(data['metrics'] ?? {}),
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'authorId': authorId,
      'authorName': authorName,
      'coverUrl': coverUrl,
      'genres': genres,
      'tags': tags,
      'league': league,
      'status': status.name,
      'language': language,
      'wordCount': wordCount,
      'chapterCount': chapterCount,
      'readerCount': readerCount,
      'completionRate': completionRate,
      'averageRating': averageRating,
      'ratingCount': ratingCount,
      'reviewCount': reviewCount,
      'favoriteCount': favoriteCount,
      'commentCount': commentCount,
      'createdAt': Timestamp.fromDate(createdAt),
      'updatedAt': Timestamp.fromDate(updatedAt),
      'publishedAt': publishedAt != null ? Timestamp.fromDate(publishedAt!) : null,
      'lastReadAt': lastReadAt != null ? Timestamp.fromDate(lastReadAt!) : null,
      'isPremium': isPremium,
      'unlockPrice': unlockPrice,
      'audioAvailable': audioAvailable,
      'qualityScore': qualityScore,
      'promotionHistory': promotionHistory,
      'metrics': metrics.toMap(),
    };
  }

  StoryModel copyWith({
    String? id,
    String? title,
    String? description,
    String? authorId,
    String? authorName,
    String? coverUrl,
    List<String>? genres,
    List<String>? tags,
    String? league,
    StoryStatus? status,
    String? language,
    int? wordCount,
    int? chapterCount,
    int? readerCount,
    double? completionRate,
    double? averageRating,
    int? ratingCount,
    int? reviewCount,
    int? favoriteCount,
    int? commentCount,
    DateTime? createdAt,
    DateTime? updatedAt,
    DateTime? publishedAt,
    DateTime? lastReadAt,
    bool? isPremium,
    double? unlockPrice,
    bool? audioAvailable,
    double? qualityScore,
    List<String>? promotionHistory,
    StoryMetrics? metrics,
  }) {
    return StoryModel(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      authorId: authorId ?? this.authorId,
      authorName: authorName ?? this.authorName,
      coverUrl: coverUrl ?? this.coverUrl,
      genres: genres ?? this.genres,
      tags: tags ?? this.tags,
      league: league ?? this.league,
      status: status ?? this.status,
      language: language ?? this.language,
      wordCount: wordCount ?? this.wordCount,
      chapterCount: chapterCount ?? this.chapterCount,
      readerCount: readerCount ?? this.readerCount,
      completionRate: completionRate ?? this.completionRate,
      averageRating: averageRating ?? this.averageRating,
      ratingCount: ratingCount ?? this.ratingCount,
      reviewCount: reviewCount ?? this.reviewCount,
      favoriteCount: favoriteCount ?? this.favoriteCount,
      commentCount: commentCount ?? this.commentCount,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      publishedAt: publishedAt ?? this.publishedAt,
      lastReadAt: lastReadAt ?? this.lastReadAt,
      isPremium: isPremium ?? this.isPremium,
      unlockPrice: unlockPrice ?? this.unlockPrice,
      audioAvailable: audioAvailable ?? this.audioAvailable,
      qualityScore: qualityScore ?? this.qualityScore,
      promotionHistory: promotionHistory ?? this.promotionHistory,
      metrics: metrics ?? this.metrics,
    );
  }

  static StoryModel fromEntity(Story story) {
    return StoryModel(
      id: story.id,
      title: story.title,
      description: story.description,
      authorId: story.authorId,
      authorName: story.authorName,
      coverUrl: story.coverUrl,
      genres: story.genres,
      tags: story.tags,
      league: story.league,
      status: story.status,
      language: story.language,
      wordCount: story.wordCount,
      chapterCount: story.chapterCount,
      readerCount: story.readerCount,
      completionRate: story.completionRate,
      averageRating: story.averageRating,
      ratingCount: story.ratingCount,
      reviewCount: story.reviewCount,
      favoriteCount: story.favoriteCount,
      commentCount: story.commentCount,
      createdAt: story.createdAt,
      updatedAt: story.updatedAt,
      publishedAt: story.publishedAt,
      lastReadAt: story.lastReadAt,
      isPremium: story.isPremium,
      unlockPrice: story.unlockPrice,
      audioAvailable: story.audioAvailable,
      qualityScore: story.qualityScore,
      promotionHistory: story.promotionHistory,
      metrics: story.metrics,
    );
  }
}
